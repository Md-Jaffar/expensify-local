// scripts/audit-deployment.mjs — Deployment and PWA Manifest Audit Script
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const distDir = path.resolve(__dirname, '../dist');

console.log('====================================================');
console.log('EXPENSIFY LOCAL — STATIC DEPLOYMENT & PWA AUDIT');
console.log('====================================================\n');

let passCount = 0;
let failCount = 0;

function assert(condition, message) {
  if (condition) {
    console.log(`  ✓ PASS: ${message}`);
    passCount++;
  } else {
    console.error(`  ✗ FAIL: ${message}`);
    failCount++;
  }
}

// 1. Verify dist files exist
const requiredFiles = [
  'index.html',
  'manifest.webmanifest',
  'sw.js',
  'registerSW.js',
  'icon.svg',
  'icon-192x192.png',
  'icon-512x512.png',
  'icon-maskable-512x512.png',
];

for (const f of requiredFiles) {
  const filePath = path.join(distDir, f);
  const exists = fs.existsSync(filePath);
  assert(exists, `Required file ${f} exists in dist/`);
}

// 2. Audit index.html
const indexHtmlPath = path.join(distDir, 'index.html');
const indexHtml = fs.readFileSync(indexHtmlPath, 'utf8');

assert(indexHtml.includes('viewport-fit=cover'), 'index.html contains viewport-fit=cover for Android edge-to-edge');
assert(indexHtml.includes('theme-color'), 'index.html contains theme-color meta tag');
assert(indexHtml.includes('manifest.webmanifest'), 'index.html links to manifest.webmanifest');
assert(indexHtml.includes('icon-192x192.png'), 'index.html references 192x192 PNG icon');
assert(indexHtml.includes('registerSW.js'), 'index.html registers service worker script');
assert(indexHtml.includes('/expensify-local/'), 'index.html uses scoped base path /expensify-local/');

// 3. Audit manifest.webmanifest
const manifestPath = path.join(distDir, 'manifest.webmanifest');
const manifestContent = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));

assert(manifestContent.name === 'Expensify Local', 'Manifest name is "Expensify Local"');
assert(manifestContent.short_name === 'Expensify', 'Manifest short_name is "Expensify"');
assert(manifestContent.display === 'standalone', 'Manifest display is "standalone" for native app experience');
assert(manifestContent.orientation === 'portrait', 'Manifest orientation is "portrait"');
assert(manifestContent.start_url === '/expensify-local/', 'Manifest start_url is scoped to /expensify-local/');
assert(manifestContent.scope === '/expensify-local/', 'Manifest scope is scoped to /expensify-local/');
assert(manifestContent.theme_color === '#0f766e', 'Manifest theme_color matches Stitch brand token #0f766e');
assert(manifestContent.background_color === '#faf8ff', 'Manifest background_color matches Stitch background token #faf8ff');

// Check icons in manifest
const icons = manifestContent.icons || [];
const has192 = icons.some((i) => i.sizes === '192x192' && i.type === 'image/png');
const has512 = icons.some((i) => i.sizes === '512x512' && i.type === 'image/png');
const hasMaskable = icons.some((i) => (i.purpose || '').includes('maskable'));

assert(has192, 'Manifest includes 192x192 PNG icon');
assert(has512, 'Manifest includes 512x512 PNG icon');
assert(hasMaskable, 'Manifest includes maskable icon for Android adaptive shapes');

for (const icon of icons) {
  const iconOnDisk = path.join(distDir, icon.src);
  const exists = fs.existsSync(iconOnDisk);
  const size = exists ? fs.statSync(iconOnDisk).size : 0;
  assert(exists && size > 0, `Icon asset "${icon.src}" exists on disk (${size} bytes)`);
}

// 4. Audit registerSW.js
const registerSWContent = fs.readFileSync(path.join(distDir, 'registerSW.js'), 'utf8');
assert(
  registerSWContent.includes("/expensify-local/sw.js") && registerSWContent.includes("scope: '/expensify-local/'"),
  'registerSW.js registers sw.js scoped to /expensify-local/'
);

// 5. Audit sw.js (precaching)
const swContent = fs.readFileSync(path.join(distDir, 'sw.js'), 'utf8');
assert(swContent.includes('workbox'), 'sw.js is generated by Workbox with precache runtime');

console.log(`\n====================================================`);
console.log(`AUDIT RESULTS: ${passCount} PASSED, ${failCount} FAILED`);
console.log(`====================================================\n`);

if (failCount > 0) {
  process.exit(1);
}
